def _norm_hint(s: str) -> str:
    return " ".join(s.replace(",", " ").split())


_PROVIDER = {_norm_hint(k): v for k, v in PROVIDER_CATEGORIES.items()}
PAIRS: list[tuple[str, str]] = [(p, c) for c, ps in DEFAULT_RULES.items() for p in ps]


def provider_category(hint: str | None) -> str | None:
    return _PROVIDER.get(_norm_hint(hint or ""))


def match_default(description: str, provider: str | None = None) -> str | None:
    """In-memory: the category the defaults alone give a description (rules, then provider)."""
    key, desc = normalize_merchant(description), description.lower()
    return best_match(PAIRS, key, desc) or provider_category(provider)


def coverage(descriptions: Iterable[str]) -> tuple[Counter, list[str]]:
    """Defaults-only coverage of descriptions: (category -> count, unmatched descriptions)."""
    hits, missed = Counter(), []
    for d in descriptions:
        if c := match_default(d):
            hits[c] += 1
        else:
            missed.append(d)
    return hits, missed


def apply_defaults(conn) -> tuple[int, int, int]:
    """Sync source='default' contains-rules with DEFAULT_RULES (a Connection or Session).
    Inserts missing ones, re-points changed ones, drops retired ones; never touches other
    sources (a user/seed rule with the same pattern wins). Returns (added, updated, removed)."""
    cats = dict(conn.execute(text("SELECT name, id FROM categories")).all())
    want = {p: cats[c] for p, c in PAIRS if c in cats}
    have = dict(
        conn.execute(
            text("SELECT pattern, category_id FROM merchant_rules WHERE match = 'contains'")
        ).all()
    )
    mine = set(
        conn.execute(
            text(
                "SELECT pattern FROM merchant_rules WHERE match = 'contains' AND source = 'default'"
            )
        ).scalars()
    )
    add = [{"p": p, "c": c} for p, c in want.items() if p not in have]
    upd = [{"p": p, "c": c} for p, c in want.items() if p in mine and have[p] != c]
    drop = [p for p in mine if p not in want]
    if add:
        conn.execute(
            text(
                "INSERT INTO merchant_rules (pattern, match, category_id, source) "
                "VALUES (:p, 'contains', :c, 'default') ON CONFLICT (pattern, match) DO NOTHING"
            ),
            add,
        )
    if upd:
        conn.execute(
            text(
                "UPDATE merchant_rules SET category_id = :c "
                "WHERE pattern = :p AND match = 'contains' AND source = 'default'"
            ),
            upd,
        )
    for p in drop:
        conn.execute(
            text(
                "DELETE FROM merchant_rules "
                "WHERE pattern = :p AND match = 'contains' AND source = 'default'"
            ),
            {"p": p},
        )
    return len(add), len(upd), len(drop)
